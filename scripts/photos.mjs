/*
  Prepares the site's photos. Run it with  ./dev.sh photos  after adding or
  replacing pictures in the photos/ folder (any .jpg, .png, .webp or .heic).

  For every photo it writes two sizes of WebP into src/assets/photos/, and
  generates src/assets/photos/index.ts listing them with their dimensions and a
  tiny blurred preview that shows while the real image loads.

  Nothing hidden survives: camera model, date and GPS location are all dropped,
  because only pixels are copied across. Black letterbox bars (from video
  stills) are trimmed off. The originals in photos/ are never committed.
*/
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const SRC = "photos";
const OUT = "src/assets/photos";
const WIDTHS = [640, 1280, 1920];

/** True when the top and bottom edges are solid black bars. */
async function hasLetterbox(file) {
  const { width, height } = await sharp(file).metadata();
  // stats() reads the whole input, so the strip is cut out into its own image first.
  const edgeIsBlack = async (top) => {
    const strip = await sharp(file).extract({ left: 0, top, width, height: 4 }).png().toBuffer();
    return (await sharp(strip).stats()).channels.slice(0, 3).every((c) => c.mean < 12);
  };
  return (await edgeIsBlack(0)) && (await edgeIsBlack(height - 4));
}

const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());

const files = (await readdir(SRC)).filter((f) => /\.(jpe?g|png|webp|heic|avif)$/i.test(f)).sort();
if (!files.length) throw new Error(`No photos found in ${SRC}/`);

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });

const entries = [];
for (const file of files) {
  const input = path.join(SRC, file);
  const name = path.parse(file).name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

  // Upright, trimmed, and decoded to raw pixels: from here on no metadata exists.
  let pipeline = sharp(input).rotate();
  if (await hasLetterbox(input)) pipeline = pipeline.trim({ background: "#000000", threshold: 24 });
  const { data, info } = await pipeline.raw().toBuffer({ resolveWithObject: true });
  const pixels = () => sharp(data, { raw: { width: info.width, height: info.height, channels: info.channels } });

  const widths = [...new Set(WIDTHS.map((w) => Math.min(w, info.width)))];
  for (const w of widths) {
    await pixels().resize({ width: w }).webp({ quality: 80, effort: 6 }).toFile(path.join(OUT, `${name}-${w}.webp`));
  }
  const blur = await pixels().resize({ width: 16 }).webp({ quality: 40 }).toBuffer();
  entries.push({ name, width: info.width, height: info.height, widths, blur: `data:image/webp;base64,${blur.toString("base64")}` });
  console.log(`  ${name}  ${info.width}×${info.height}`);
}

const imports = entries.flatMap((e) => e.widths.map((w) => `import ${camel(e.name)}${w} from "./${e.name}-${w}.webp";`));
const body = entries.map((e) => {
  const v = (w) => `${camel(e.name)}${w}`;
  const srcset = e.widths.map((w) => `\${${v(w)}} ${w}w`).join(", ");
  return `  "${e.name}": { width: ${e.width}, height: ${e.height}, src: ${v(e.widths.at(-1))}, srcset: \`${srcset}\`, blur: "${e.blur}" },`;
});

await writeFile(
  path.join(OUT, "index.ts"),
  `// Generated by scripts/photos.mjs. Don't edit: add photos to photos/ and run ./dev.sh photos.
${imports.join("\n")}

export type PhotoFile = { width: number; height: number; src: string; srcset: string; blur: string };

export const photoFiles = {
${body.join("\n")}
} satisfies Record<string, PhotoFile>;

export type PhotoName = keyof typeof photoFiles;
`,
);
console.log(`\n${entries.length} photos written to ${OUT}/`);
